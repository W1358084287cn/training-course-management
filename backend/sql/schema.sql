CREATE TABLE IF NOT EXISTS `组织机构` (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  name VARCHAR(128) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uk_org_name (name)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS `用户` (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  org_id BIGINT UNSIGNED NOT NULL,
  username VARCHAR(64) NOT NULL,
  password_hash VARCHAR(255) NOT NULL,
  role ENUM('admin','coach') NOT NULL DEFAULT 'coach',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uk_user_org_username (org_id, username),
  KEY idx_user_org (org_id),
  CONSTRAINT fk_users_org FOREIGN KEY (org_id) REFERENCES `组织机构` (id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS `会员` (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  org_id BIGINT UNSIGNED NOT NULL,
  name VARCHAR(128) NOT NULL,
  card_type VARCHAR(128) NOT NULL,
  age VARCHAR(32) NULL,
  start_date VARCHAR(32) NOT NULL,
  end_date VARCHAR(32) NOT NULL,
  total_classes INT NOT NULL DEFAULT 0,
  remaining_classes INT NOT NULL DEFAULT 0,
  remark TEXT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  KEY idx_members_org (org_id),
  KEY idx_members_org_name (org_id, name),
  CONSTRAINT fk_members_org FOREIGN KEY (org_id) REFERENCES `组织机构` (id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS `活动课程` (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  org_id BIGINT UNSIGNED NOT NULL,
  name VARCHAR(128) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uk_activities_org_name (org_id, name),
  KEY idx_activities_org (org_id),
  CONSTRAINT fk_activities_org FOREIGN KEY (org_id) REFERENCES `组织机构` (id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS `活动会员记录` (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  org_id BIGINT UNSIGNED NOT NULL,
  activity_id BIGINT UNSIGNED NOT NULL,
  name VARCHAR(128) NOT NULL,
  card_type VARCHAR(128) NOT NULL,
  age VARCHAR(32) NULL,
  start_date VARCHAR(32) NOT NULL,
  end_date VARCHAR(32) NOT NULL,
  total_classes INT NOT NULL DEFAULT 0,
  remaining_classes INT NOT NULL DEFAULT 0,
  remark TEXT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  KEY idx_activity_members_org (org_id),
  KEY idx_activity_members_activity (activity_id),
  CONSTRAINT fk_activity_member_records_org FOREIGN KEY (org_id) REFERENCES `组织机构` (id) ON DELETE CASCADE,
  CONSTRAINT fk_activity_member_records_activity FOREIGN KEY (activity_id) REFERENCES `活动课程` (id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS `排课时段` (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  org_id BIGINT UNSIGNED NOT NULL,
  time VARCHAR(32) NOT NULL,
  monday VARCHAR(255) NULL,
  tuesday VARCHAR(255) NULL,
  wednesday VARCHAR(255) NULL,
  thursday VARCHAR(255) NULL,
  friday VARCHAR(255) NULL,
  saturday VARCHAR(255) NULL,
  sunday VARCHAR(255) NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
